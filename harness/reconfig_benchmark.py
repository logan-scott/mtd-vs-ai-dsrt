# State generation (pure; offline-testable)
# --------------------------------------------------------------------------- #


def generate_state_pair(
    condition: str, profile: ConfigState, seed: int
) -> tuple[ConfigState, ConfigState]:
    """``(s1, s2)`` = the technique applied to the profile once, then to that result again.

    One RNG drives both applications, mirroring the orchestrator's single-RNG cadence loop
    (two consecutive ticks). ``s1`` is applied untimed and ``s2`` timed, so the measured
    reconfiguration is ``s1 -> s2``: exactly one technique-``condition`` mutation, regardless
    of the substrate's prior state. For ``static_baseline`` the technique is the identity, so
    ``state_checksum(s1) == state_checksum(s2)`` and the timed application is a no-op.
    """

    technique = get_technique(condition)
    rng = random.Random(seed)
    s1, _ = technique(profile, rng)
    s2, _ = technique(s1, rng)
    return s1, s2


