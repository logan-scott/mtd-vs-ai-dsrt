def wait_until_ready(
    host: str,
    port: int,
    *,
    interval_s: float,
    timeout_s: float,
    connect_timeout_s: float = 1.0,
) -> dict:
    """Poll ``host:port`` until a TCP connect succeeds, or the timeout expires.

    Runs OUTSIDE the timed region, after the untimed setup apply, so the monitored service is
    actually serving before the probe + timed apply start. "Ready" is a TCP connect — the SAME
    signal ``AvailabilityProbe`` counts as available, so readiness and the probe agree by
    construction (an HTTP-level check would measure something the TCP probe does not, and the
    probe is what the availability figure is built from). Returns ``settle_wait_s`` (how long the
    setup step took to serve — the direct measure of predecessor contamination) and ``ready``
    (False = the timeout expired, so this replicate's availability is unusable, not zero).
    """

    start = time.perf_counter()
    deadline = start + timeout_s
    while True:
        try:
            with socket.create_connection((host, port), timeout=connect_timeout_s):
                return {"settle_wait_s": round(time.perf_counter() - start, 4), "ready": True}
        except OSError:
            pass
        if time.perf_counter() >= deadline:
            return {"settle_wait_s": round(time.perf_counter() - start, 4), "ready": False}
        time.sleep(interval_s)


def replicate_seed(seed: int, condition: str, replicate: int) -> int:
    """The seed of one (technique, replicate): the same in every process and on every host.

    Until 2026-10-31 this used Python's ``hash((condition, replicate))``, which is salted per
    process (``PYTHONHASHSEED``), so a rerun drew different state pairs although the comment
    said otherwise. Each record's ``seed`` still reproduces its own pair either way.
    """

    return (seed * 0x9E3779B1 + zlib.crc32(f"{condition}:{replicate}".encode())) & 0xFFFFFFFF


def published_ports(state: ConfigState) -> list[int]:
    """Every port the state publishes on the targets host (genuine services and decoys)."""

    return sorted({s.port for s in state.services})


def wait_until_all_ready(
    host: str,
    ports: list[int],
    *,
    interval_s: float,
    timeout_s: float,
    connect_timeout_s: float = 1.0,
) -> dict:
    """Wait until EVERY port answers a TCP connect (``wait_until_ready``, for all of them).

    The settle step before the timed apply. Until 2026-10-31 it waited for the monitored
    service alone, so after an untimed port change another container (Juice Shop, WebGoat)
    could still be starting when the timed reconfiguration began. Same return shape as
    ``wait_until_ready``: ``settle_wait_s`` until the last port answered, ``ready``.
    """

    start = time.perf_counter()
    deadline = start + timeout_s
    pending = set(ports)
    while True:
        for port in sorted(pending):
            try:
                with socket.create_connection((host, port), timeout=connect_timeout_s):
                    pending.discard(port)
            except OSError:
                pass
        if not pending:
            return {"settle_wait_s": round(time.perf_counter() - start, 4), "ready": True}
        if time.perf_counter() >= deadline:
            return {"settle_wait_s": round(time.perf_counter() - start, 4), "ready": False}
        time.sleep(interval_s)


@dataclass
class AvailabilityProbe:
    """Probe ONE genuine service across its old and new published ports during a reconfig.

    The service counts available in an interval if a TCP connect to EITHER the pre-reconfig
    port (``port_a``) or the post-reconfig port (``port_b``) succeeds. Trying both ports is
    what distinguishes "the port moved" (one or the other always answers, availability ≈ 1)
    from "the service was down" (neither answers during container recreation, availability
    dips). Runs in a background thread so it samples the whole reconfiguration window.
    """

    host: str
    port_a: int
    port_b: int
    interval_s: float = 0.1
    connect_timeout_s: float = 0.25
    _stop: threading.Event = field(default_factory=threading.Event, init=False)
    _thread: threading.Thread | None = field(default=None, init=False)
    answered: int = field(default=0, init=False)
    total: int = field(default=0, init=False)

    def _one_probe(self) -> bool:
        for port in {self.port_a, self.port_b}:
            try:
                with socket.create_connection((self.host, port), timeout=self.connect_timeout_s):
                    return True
            except OSError:
                continue
        return False

    def _loop(self) -> None:
        while not self._stop.is_set():
            ok = self._one_probe()
            self.total += 1
            if ok:
                self.answered += 1
            self._stop.wait(self.interval_s)

    def start(self) -> None:
        self._thread = threading.Thread(target=self._loop, daemon=True)
        self._thread.start()

    def stop(self) -> dict:
        self._stop.set()
        if self._thread is not None:
            self._thread.join(timeout=5.0)
        fraction = (self.answered / self.total) if self.total else None
        return {
            "availability_during_reconfig": fraction,
            "probes_answered": self.answered,
            "probes_total": self.total,
            "probe_port_a": self.port_a,
            "probe_port_b": self.port_b,
        }


