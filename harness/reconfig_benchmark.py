"""Reconfiguration-cost benchmark: the technique-intrinsic cost of ONE reconfiguration.

This is the MEASURED replacement for the synthetic operational-cost telemetry
(``harness.telemetry``; see ``docs/metrics_specification.md`` §3). The synthetic generator
made cost a linear function of the reconfiguration-event count — uniform across MTD
conditions at equal cadence. Direct measurement on the targets node shows the opposite:
cost is driven by whether a technique mutates a *published port* (so containers must be
recreated), and it discriminates by roughly three orders of magnitude
(``static_baseline`` ≈ a checksum no-op; ``network_shuffling`` / ``endpoint_mutation`` ≈ 1 s,
no restart; ``port_rotation`` / ``combined_mtd_deception`` ≈ 30 s, every published container
recreated).

DESIGN — consecutive application. For each technique, two successive states are generated by
applying that technique TWICE to the pristine profile (one RNG, like the orchestrator's
cadence loop): ``s1 = T(profile)``, ``s2 = T(s1)``. The first is applied UNTIMED (it moves
the substrate to ``s1`` regardless of whatever predecessor state the previous replicate left
behind — which is why technique order can be randomized), and the SECOND is TIMED. The timed
application therefore measures exactly one technique-``T`` reconfiguration, not the diff
against an arbitrary predecessor. ``static_baseline`` is the identity, so ``s1 == s2`` by
checksum and its timed application is a checksum no-op — the benchmark's internal control:
if it ever registers a non-trivial cost, the consecutive-application logic has broken.

This module is split like ``harness.cost_probe``: pure, offline-testable helpers
(``generate_state_pair``, ``summarize``, output writers, parsers) separated from the
Docker-touching execution (``run_benchmark`` / ``apply_state`` / ``AvailabilityProbe``), which
runs only on a provisioned targets node. It reuses ``harness.live_runner.desired_config_for_state``
so the benchmarked reconfiguration is byte-identical to the one the study runs, and the
``harness.safety.assert_within_cidr`` allowlist so nothing is ever probed or reconfigured
outside the sealed testbed. ``run_benchmark`` restores the pristine profile on exit, so a
subsequent study run is not contaminated.
"""

