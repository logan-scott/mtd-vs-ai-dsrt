# Compose emits SEVERAL progress lines per container on `up -d` -- e.g. a recreated
# container prints "Recreate" -> "Recreated" -> "Starting" -> "Started", an untouched one
# prints only "Running", a fresh one "Creating"/"Created"/"Starting"/"Started". So the lines
# must be DEDUPED BY CONTAINER NAME before counting, or a single recreated container counts
# three or four times (5 genuine services read as 15). A container is "recreated" if any of
# its status words is a (re)create/start word; "running" iff it only ever reported Running.
_RECREATE_WORDS = frozenset(
    {
        "Recreate",
        "Recreated",
        "Recreating",
        "Create",
        "Created",
        "Creating",
        "Start",
        "Started",
        "Starting",
    }
)
_RUNNING_WORDS = frozenset({"Running"})
_CONTAINER_LINE = re.compile(r"Container\s+(\S+)\s+(\w+)")
_NOOP_MARKER = "no-op"


def parse_reconfigure_output(text: str) -> dict:
    """Parse reconfigure.sh (+ compose) output into restart bookkeeping.

    Returns ``n_recreated`` / ``n_running`` -- DISTINCT containers that were recreated vs left
    in place (deduped by container name across compose's multi-phase progress lines) -- and
    ``checksum_noop`` (the reconfigure short-circuited on a matching checksum, so nothing was
    rendered or reconciled at all). Compose emits the per-container status on stderr; the
    caller passes stdout+stderr concatenated.
    """

    noop = _NOOP_MARKER in text
    statuses: dict[str, set[str]] = {}
    for name, status in _CONTAINER_LINE.findall(text):
        statuses.setdefault(name, set()).add(status)
    recreated = sum(1 for words in statuses.values() if words & _RECREATE_WORDS)
    running = sum(
        1
        for words in statuses.values()
        if (words & _RUNNING_WORDS) and not (words & _RECREATE_WORDS)
    )
    return {
        "n_recreated": recreated,
        "n_running": running,
        "n_containers_seen": len(statuses),
        "checksum_noop": noop,
    }


