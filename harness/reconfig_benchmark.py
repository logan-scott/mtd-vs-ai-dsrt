def _settle_summary(values: list) -> dict:
    """Mean/median/max/values for the per-replicate setup settle times (ignoring None)."""

    vals = [v for v in values if v is not None]
    if not vals:
        return {"n": 0, "mean": None, "median": None, "max": None, "values": []}
    return {
        "n": len(vals),
        "mean": round(statistics.fmean(vals), 4),
        "median": round(statistics.median(vals), 4),
        "max": round(max(vals), 4),
        "values": [round(v, 4) for v in vals],
    }


def _ci95_mean(values: list[float]) -> tuple[float, float] | None:
    """A 95% CI for the mean via the normal approximation (n>=2); None otherwise."""

    n = len(values)
    if n < 2:
        return None
    mean = statistics.fmean(values)
    sd = statistics.stdev(values)
    half = 1.96 * sd / (n**0.5)
    return (mean - half, mean + half)


def _iqr(values: list[float]) -> tuple[float, float]:
    q = statistics.quantiles(values, n=4) if len(values) >= 2 else [values[0], values[0]]
    return (q[0], q[2])


def summarize(records: list[dict]) -> dict:
    """Per-technique summary + a between-technique test suitable for the realized data.

    Reports mean AND median/IQR (the distributions are expected to be bimodal — restart vs
    no-restart) plus a 95% CI, mean availability during reconfiguration, and the restart-count
    distribution so a reader can see the mechanism. The between-technique test is
    Kruskal–Wallis (non-parametric): the per-technique distributions are non-normal and can be
    multi-modal, so a rank test on the realized values is the defensible omnibus.
    """

    by_tech: dict[str, list[dict]] = {}
    for r in records:
        by_tech.setdefault(r["technique"], []).append(r)

    per_technique: dict[str, dict] = {}
    for tech, rows in by_tech.items():
        wall = [r["wall_clock_s"] for r in rows]
        avail = [
            r["availability_during_reconfig"]
            for r in rows
            if r["availability_during_reconfig"] is not None
        ]
        restart_dist: dict[int, int] = {}
        for r in rows:
            restart_dist[r["n_containers_recreated"]] = (
                restart_dist.get(r["n_containers_recreated"], 0) + 1
            )
        ci = _ci95_mean(wall)
        iqr = _iqr(wall)
        per_technique[tech] = {
            "n": len(wall),
            "wall_clock_s": {
                "mean": round(statistics.fmean(wall), 4),
                "sd": round(statistics.stdev(wall), 4) if len(wall) >= 2 else None,
                "median": round(statistics.median(wall), 4),
                "iqr": [round(iqr[0], 4), round(iqr[1], 4)],
                "ci95": [round(ci[0], 4), round(ci[1], 4)] if ci else None,
                "min": round(min(wall), 4),
                "max": round(max(wall), 4),
            },
            "mean_availability_during_reconfig": (
                round(statistics.fmean(avail), 4) if avail else None
            ),
            # Availability with its provenance + spread. Only MEASURED replicates enter the mean;
            # no-op (static_baseline) and setup-not-ready replicates are reported separately and
            # never folded in as a fabricated value.
            "availability": {
                "n_measured": len(avail),
                "mean": round(statistics.fmean(avail), 4) if avail else None,
                "min": round(min(avail), 4) if avail else None,
                "max": round(max(avail), 4) if avail else None,
                "values": [round(v, 4) for v in avail],
                "n_not_applicable_noop": sum(
                    1 for r in rows if r.get("availability_status") == AVAIL_NOT_APPLICABLE_NOOP
                ),
                "n_unusable_not_ready": sum(
                    1 for r in rows if r.get("availability_status") == AVAIL_UNUSABLE_NOT_READY
                ),
            },
            # Setup settle time (OUTSIDE the timed cost) — the direct measure of how much
            # predecessor contamination a run carried: a long settle means the setup apply
            # recreated the monitored container before this replicate was timed.
            "settle_wait_s": _settle_summary([r.get("settle_wait_s") for r in rows]),
            "restart_count_distribution": {str(k): v for k, v in sorted(restart_dist.items())},
            "checksum_noop_count": sum(1 for r in rows if r["checksum_noop"]),
        }

    return {
        "per_technique": per_technique,
        "between_technique_test": _between_technique_test(by_tech),
        "n_replicates_total": len(records),
    }


def _between_technique_test(by_tech: dict[str, list[dict]]) -> dict:
    """Kruskal–Wallis H across techniques on wall-clock cost (non-parametric omnibus)."""

    groups = [[r["wall_clock_s"] for r in rows] for rows in by_tech.values()]
    groups = [g for g in groups if len(g) >= 1]
    if len(groups) < 2:
        return {"test": "kruskal_wallis", "note": "fewer than two techniques"}
    # A rank test needs variation; if every value is identical it is undefined.
    if len({v for g in groups for v in g}) < 2:
        return {"test": "kruskal_wallis", "note": "no variation across techniques"}
    try:
        from scipy.stats import kruskal

        h, p = kruskal(*groups)
        return {
            "test": "kruskal_wallis",
            "reason": "non-parametric: per-technique cost is non-normal and can be bimodal "
            "(restart vs no-restart), so a rank-based omnibus is used on the realized values",
            "H": round(float(h), 4),
            "p_value": float(p),
            "k_groups": len(groups),
        }
    except ImportError:  # pragma: no cover - scipy is in the analysis stack
        return {"test": "kruskal_wallis", "note": "scipy unavailable"}


