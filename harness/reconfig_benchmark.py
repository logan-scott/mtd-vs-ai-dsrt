#: The six study conditions, in the documented order. Used as the default technique set so
#: the common case is a short command and a bare ``BenchmarkConfig()`` is valid (the operator's
#: first attempt failed on a required positional ``techniques`` when hand-driving the class).
DEFAULT_TECHNIQUES: tuple[str, ...] = tuple(CONDITIONS)

#: Benchmark version, stamped into metadata.json so runs can never be confused. Bumped to 2
#: when the readiness settle (Part 1) + no-op availability handling (Part 2) landed: v1 runs
#: (which lack this key in metadata.json) carry a CONTAMINATED availability column that sampled
#: the setup step's container startup, not the technique. Cost/restart data in v1 are sound.
#: Bumped to 3 (2026-10-31) when the settle began waiting for every published service of the
#: setup state, not the monitored one alone, and the replicate seeds stopped depending on
#: Python's per-process hash salt (``replicate_seed``); a v2 run carries ``benchmark_version: 2``.
BENCHMARK_VERSION = 3

# availability_status values.
AVAIL_MEASURED = "measured"
AVAIL_NOT_APPLICABLE_NOOP = "not_applicable_noop"  # a checksum no-op has no reconfiguration window
AVAIL_UNUSABLE_NOT_READY = "unusable_setup_not_ready"  # the setup apply never settled in time


@dataclass(frozen=True)
class BenchmarkConfig:
    """Where and how to run the benchmark. Defaults target the real sealed testbed node."""

    techniques: tuple[str, ...] = DEFAULT_TECHNIQUES
    replicates: int = 20
    testbed_dir: str = "/opt/testbed"
    reconfigure_sh: str = "/opt/testbed/reconfigure.sh"
    targets_host: str = "172.31.66.10"
    bind_host: str = "172.31.66.10"
    testbed_cidr: str = "172.31.66.0/24"
    vuln_profile_version: str = "vp-0.2.0"
    # The genuine service whose availability is probed across the reconfiguration (it is
    # recreated by the port-mutating techniques, stable under the others).
    monitored_service_id: str = "dvwa"
    probe_interval_s: float = 0.1
    reconfigure_timeout_s: float = 180.0
    # Readiness settle (OUTSIDE the timed region): after the untimed setup apply moves the
    # substrate to s1, wait until every published service of s1 answers before starting the
    # probe + timed apply, so the probe measures the TECHNIQUE and not the setup step's
    # container startup. 300 s (90 s until 2026-10-31, when the settle covered the monitored
    # service alone) matches the study's own readiness gate (live.readiness_timeout_s): the
    # settle now also waits for the JVM-class WebGoat and for Juice Shop.
    readiness_interval_s: float = 0.5
    readiness_timeout_s: float = 300.0
    readiness_connect_timeout_s: float = 1.0
    seed: int = 1


def _desired_path(cfg: BenchmarkConfig, desired: dict) -> Path:
    """Where to stage the desired-state JSON — mirrors reconfigure.yml's own path."""

    state_dir = Path(cfg.testbed_dir) / "state"
    state_dir.mkdir(parents=True, exist_ok=True)
    return state_dir / f"desired-{desired['config_checksum']}.json"


def apply_state(cfg: BenchmarkConfig, condition: str, state: ConfigState, *, timed: bool) -> dict:
    """Apply one desired state via reconfigure.sh; when ``timed``, measure wall/CPU/RSS.

    Runs the REAL reconfigure.sh (pointed at ``cfg.testbed_dir`` / ``cfg.bind_host`` via env,
    defaults preserved for production) so the benchmark times exactly what the study runs. CPU
    and peak RSS come from ``os.wait4`` on the reconfigure.sh process tree — the client-side
    cost; the bulk of container recreation happens in the Docker daemon, which a process-tree
    rusage cannot see, so wall-clock and the availability probe are the load-bearing measures
    (documented in docs/metrics_specification.md §3).

    The timed path captures stdout/stderr to temp FILES, not pipes: ``os.wait4`` blocks until
    the child exits, so reading pipes only afterward would deadlock if ``docker compose`` wrote
    more than one pipe buffer (~64 KiB) before exiting. A watchdog timer kills the whole
    process group after ``reconfigure_timeout_s`` so a stuck daemon cannot hang the hot path
    (the untimed path gets this from ``subprocess.run(timeout=...)``, which drains concurrently).
    """

    desired = desired_config_for_state(condition, state)
    path = _desired_path(cfg, desired)
    path.write_text(json.dumps(desired, sort_keys=True), encoding="utf-8")

    env = dict(os.environ)
    env["TESTBED"] = cfg.testbed_dir
    env["BIND_HOST"] = cfg.bind_host
    argv = ["bash", cfg.reconfigure_sh, str(path)]

    if not timed:
        proc = subprocess.run(
            argv, env=env, capture_output=True, text=True, timeout=cfg.reconfigure_timeout_s
        )
        return {"returncode": proc.returncode, "stdout": proc.stdout, "stderr": proc.stderr}

    with tempfile.TemporaryFile() as out_f, tempfile.TemporaryFile() as err_f:
        t0 = time.perf_counter()
        # start_new_session so the child leads its own process group -> the watchdog can kill
        # the whole reconfigure.sh -> compose -> docker-client tree, not just bash.
        proc = subprocess.Popen(argv, env=env, stdout=out_f, stderr=err_f, start_new_session=True)
        timed_out = {"fired": False}

        def _kill_tree() -> None:
            timed_out["fired"] = True
            try:
                os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
            except (ProcessLookupError, PermissionError, OSError):  # pragma: no cover - race
                pass

        watchdog = threading.Timer(cfg.reconfigure_timeout_s, _kill_tree)
        watchdog.start()
        try:
            _pid, status, usage = os.wait4(proc.pid, 0)
        finally:
            watchdog.cancel()
        wall_s = time.perf_counter() - t0
        out_f.seek(0)
        err_f.seek(0)
        stdout = out_f.read().decode(errors="replace")
        stderr = err_f.read().decode(errors="replace")

    # ru_maxrss is bytes on macOS, kilobytes on Linux; the targets node (Linux) reports KB.
    rss_kb = usage.ru_maxrss if platform.system() == "Linux" else usage.ru_maxrss / 1024.0
    return {
        "returncode": os.waitstatus_to_exitcode(status),
        "stdout": stdout,
        "stderr": stderr,
        "wall_clock_s": wall_s,
        "cpu_user_s": usage.ru_utime,
        "cpu_sys_s": usage.ru_stime,
        "peak_rss_kb": rss_kb,
        "timed_out": timed_out["fired"],
    }


