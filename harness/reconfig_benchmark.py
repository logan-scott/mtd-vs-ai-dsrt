def _monitored_ports(cfg: BenchmarkConfig, s1: ConfigState, s2: ConfigState) -> tuple[int, int]:
    """The probed service's (pre, post) published ports, for the availability probe."""

    def _port(state: ConfigState) -> int:
        for s in state.services:
            if s.service_id == cfg.monitored_service_id:
                return s.port
        raise KeyError(f"monitored service {cfg.monitored_service_id!r} not in state")

    return _port(s1), _port(s2)


def dry_run_plan(cfg: BenchmarkConfig, profile: ConfigState | None = None) -> dict:
    """Validate the config and describe what the benchmark WOULD do, without touching Docker.

    Pure: asserts containment (``assert_within_cidr`` — raises on an out-of-CIDR targets host,
    exactly as the real run does), then generates each technique's ``s1 -> s2`` pair and reports
    the structural facts that decide the measurement — whether the timed apply is a checksum
    no-op, whether genuine / decoy published ports move (i.e. whether containers are recreated),
    and the monitored service's pre/post ports. Lets the operator confirm the command resolves
    (config loaded, args bound, testbed host in-CIDR) before committing to a real Docker run, and
    is the reachability proof for the sealed node, which lacks the analysis stack. Per-technique
    checksums are from a fixed representative seed (``cfg.seed``); the structural booleans are
    seed-independent.
    """

    assert_within_cidr([cfg.targets_host], cfg.testbed_cidr)  # fail closed, same as run_benchmark
    profile = profile or default_profile(cfg.vuln_profile_version)
    techniques: list[dict] = []
    for condition in cfg.techniques:
        s1, s2 = generate_state_pair(condition, profile, cfg.seed)
        g1 = {s.service_id: s.port for s in s1.services if s.genuine}
        g2 = {s.service_id: s.port for s in s2.services if s.genuine}
        d1 = {s.service_id: s.port for s in s1.services if not s.genuine}
        d2 = {s.service_id: s.port for s in s2.services if not s.genuine}
        port_a, port_b = _monitored_ports(cfg, s1, s2)
        techniques.append(
            {
                "technique": condition,
                "checksum_s1": state_checksum(s1),
                "checksum_s2": state_checksum(s2),
                "checksum_noop": state_checksum(s1) == state_checksum(s2),
                "genuine_ports_move": g1 != g2,
                "decoy_ports_move": d1 != d2,
                "monitored_ports": [port_a, port_b],
            }
        )
    return {
        "targets_host": cfg.targets_host,
        "bind_host": cfg.bind_host,
        "testbed_cidr": cfg.testbed_cidr,
        "testbed_dir": cfg.testbed_dir,
        "reconfigure_sh": cfg.reconfigure_sh,
        "replicates": cfg.replicates,
        "monitored_service_id": cfg.monitored_service_id,
        "representative_seed": cfg.seed,
        "techniques": techniques,
    }


def run_benchmark(cfg: BenchmarkConfig, profile: ConfigState | None = None) -> list[dict]:
    """Run the benchmark and return one record per replicate (order-randomized, pristine on exit).

    Containment is asserted up front and the testbed is restored to the pristine profile in a
    ``finally`` so a subsequent study run is never contaminated.
    """

    assert_within_cidr([cfg.targets_host], cfg.testbed_cidr)  # fail closed before any I/O
    profile = profile or default_profile(cfg.vuln_profile_version)

    # A fixed (technique, replicate_index) work-list, shuffled by a seeded RNG so thermal
    # state / page cache / image-layer caching do not load onto whichever technique is first.
    work = [(t, i) for t in cfg.techniques for i in range(cfg.replicates)]
    random.Random(cfg.seed ^ 0xBEEF).shuffle(work)

    records: list[dict] = []
    try:
        for order_index, (condition, replicate) in enumerate(work):
            # Fresh seed per (technique, replicate) so the benchmark samples the mutation
            # distribution rather than one draw; stable across reruns for reproducibility.
            rep_seed = replicate_seed(cfg.seed, condition, replicate)
            s1, s2 = generate_state_pair(condition, profile, rep_seed)

            apply_state(cfg, condition, s1, timed=False)  # untimed: move substrate to s1

            port_a, port_b = _monitored_ports(cfg, s1, s2)
            # SETTLE the setup step out of the timed region: the untimed apply above may have
            # recreated containers (if the predecessor left them on different ports). Wait until
            # EVERY published service of s1 serves -- the monitored one on port_a included --
            # BEFORE the probe + timed apply, so the probe measures the technique's disruption,
            # not the setup's startup, and the timed apply starts from a settled substrate, as
            # every study attempt does (live.surface_check: strict). Not timed; recorded.
            settle = wait_until_all_ready(
                cfg.targets_host,
                published_ports(s1),
                interval_s=cfg.readiness_interval_s,
                timeout_s=cfg.readiness_timeout_s,
                connect_timeout_s=cfg.readiness_connect_timeout_s,
            )

            probe = AvailabilityProbe(
                cfg.targets_host, port_a, port_b, interval_s=cfg.probe_interval_s
            )
            probe.start()
            timed = apply_state(cfg, condition, s2, timed=True)  # TIMED: s1 -> s2
            avail = probe.stop()

            parsed = parse_reconfigure_output(timed["stdout"] + "\n" + timed["stderr"])
            # Availability provenance. It is unusable if the setup never settled (a fraction
            # here would sample the setup, not the technique), and NOT APPLICABLE for a checksum
            # no-op (no reconfiguration window, and only ~1 probe fires). Only otherwise is the
            # probe's fraction a measurement -- never a fabricated 0 or a one-sample fraction.
            if not settle["ready"]:
                availability, avail_status = None, AVAIL_UNUSABLE_NOT_READY
            elif parsed["checksum_noop"]:
                availability, avail_status = None, AVAIL_NOT_APPLICABLE_NOOP
            else:
                availability, avail_status = avail["availability_during_reconfig"], AVAIL_MEASURED
            records.append(
                {
                    "technique": condition,
                    "replicate": replicate,
                    "order_index": order_index,
                    "seed": rep_seed,
                    "checksum_s1": state_checksum(s1),
                    "checksum_s2": state_checksum(s2),
                    "wall_clock_s": round(timed["wall_clock_s"], 4),
                    "cpu_user_s": round(timed["cpu_user_s"], 4),
                    "cpu_sys_s": round(timed["cpu_sys_s"], 4),
                    "peak_rss_kb": round(timed["peak_rss_kb"], 1),
                    "returncode": timed["returncode"],
                    "timed_out": timed.get("timed_out", False),
                    "checksum_noop": parsed["checksum_noop"],
                    "n_containers_recreated": parsed["n_recreated"],
                    "n_containers_running": parsed["n_running"],
                    "settle_wait_s": settle["settle_wait_s"],
                    "readiness_reached": settle["ready"],
                    "availability_during_reconfig": availability,
                    "availability_status": avail_status,
                    "probes_answered": avail["probes_answered"],
                    "probes_total": avail["probes_total"],
                    "probe_port_a": avail["probe_port_a"],
                    "probe_port_b": avail["probe_port_b"],
                    "host": socket.gethostname(),
                }
            )
    finally:
        # Leave the testbed pristine for the next study run (untimed; not recorded).
        apply_state(cfg, "static_baseline", profile, timed=False)

    return records


