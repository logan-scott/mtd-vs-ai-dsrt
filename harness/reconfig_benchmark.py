#: Written beside ``cli.py`` on the targets node by ``scripts/stage_reconfig_bench.sh``: the node
#: is staged without ``.git`` (no egress, no clone), so this records which commit was staged.
STAGED_COMMIT_FILE = "STAGED_COMMIT.json"


def _instrument_root() -> Path:
    return Path(__file__).resolve().parent.parent


def _git_commit() -> str | None:
    """HEAD of the instrument's git checkout (None outside one, e.g. on the staged node)."""

    try:
        out = subprocess.run(
            ["git", "-C", str(_instrument_root()), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            timeout=10,
        )
        return (out.stdout.strip() or None) if out.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):  # pragma: no cover
        return None


def _code_version() -> dict:
    """The code version the benchmark ran (C235).

    From git when it runs in a checkout. On the sealed targets node (staged without ``.git``),
    from the marker the staging script wrote, which also lists the control host's uncommitted
    changes and when it staged. Neither -> ``git_commit: null`` with no source, never a guess.
    """

    commit = _git_commit()
    if commit is not None:
        return {"git_commit": commit, "git_commit_source": "git"}
    try:
        doc = json.loads((_instrument_root() / STAGED_COMMIT_FILE).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"git_commit": None, "git_commit_source": None}
    if not isinstance(doc, dict) or not doc.get("git_commit"):
        return {"git_commit": None, "git_commit_source": None}
    return {
        "git_commit": str(doc["git_commit"]),
        "git_commit_source": "staged_marker",
        "git_uncommitted": doc.get("git_uncommitted"),
        "staged_utc": doc.get("staged_utc"),
    }


def _docker_version() -> str | None:
    try:
        out = subprocess.run(
            ["docker", "version", "--format", "{{.Server.Version}}"],
            capture_output=True,
            text=True,
            timeout=15,
        )
        return out.stdout.strip() or None
    except (OSError, subprocess.SubprocessError):  # pragma: no cover
        return None


def _image_digests(base_compose: Path) -> dict:
    """Pinned image references from the base compose file (``image:`` lines)."""

    digests: dict[str, str] = {}
    if not base_compose.exists():
        return digests
    for line in base_compose.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("image:"):
            ref = stripped.split(":", 1)[1].strip()
            digests[ref.split("@")[0].split(" ")[0]] = ref
    return digests


